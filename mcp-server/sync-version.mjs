// Generates version.ts from the plugin manifest so the MCP server reports the
// version it was shipped with. The value reaches two channels that update
// independently -- the plugin's own .mcp.json and the .mcpb desktop extension
// -- and a wrong number there makes a stale install indistinguishable from a
// current one.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const manifest = JSON.parse(
  readFileSync(new URL('../.claude-plugin/plugin.json', import.meta.url), 'utf8'),
);
const generated = `// Generated by sync-version.mjs from .claude-plugin/plugin.json. Do not edit.
export const KB_WRITER_MCP_VERSION = ${JSON.stringify(manifest.version)};
`;

const target = new URL('./version.ts', import.meta.url);
const current = (() => {
  try {
    return readFileSync(target, 'utf8');
  } catch {
    return null;
  }
})();
if (current !== generated) {
  writeFileSync(target, generated);
  process.stdout.write(`version.ts -> ${manifest.version}\n`);
} else {
  process.stdout.write(`version.ts already ${manifest.version}\n`);
}
void here;
